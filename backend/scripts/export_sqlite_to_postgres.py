import os
import sys
from datetime import date, datetime
from pathlib import Path

from sqlalchemy import create_engine, inspect, text
from sqlalchemy.orm import Session

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.db.base import Base  # noqa: E402
from app.models import AuditLog, Booking, Departure, Review, Tour, User  # noqa: E402

MODELS = [User, Tour, Departure, Booking, Review, AuditLog]


def sql_value(value, column=None) -> str:
    if value is None:
        return "NULL"
    if column is not None and getattr(column.type, "python_type", None) is bool:
        return "TRUE" if bool(value) else "FALSE"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (datetime, date)):
        value = value.isoformat(sep=" ") if isinstance(value, datetime) else value.isoformat()
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return str(value)
    escaped = str(value).replace("'", "''")
    return f"'{escaped}'"


def main() -> None:
    sqlite_path = Path(os.getenv("SQLITE_PATH", "dalat_go.db")).resolve()
    output_path = Path(os.getenv("OUTPUT_SQL", "sqlite_export.sql")).resolve()
    if not sqlite_path.exists():
        raise FileNotFoundError(sqlite_path)

    engine = create_engine(f"sqlite:///{sqlite_path}")
    inspector = inspect(engine)
    existing_tables = set(inspector.get_table_names())

    lines = [
        "-- DALAT Go SQLite export for PostgreSQL",
        f"-- Source: {sqlite_path}",
        "-- Generated by scripts/export_sqlite_to_postgres.py",
        "BEGIN;",
        "",
    ]

    # Schema is generated from the SQLAlchemy models and is safe to run on an empty PostgreSQL DB.
    schema_lines: list[str] = []
    # Use PostgreSQL dialect without connecting to the server.
    from sqlalchemy.schema import CreateTable
    from sqlalchemy.dialects import postgresql
    for model in MODELS:
        schema_lines.append(str(CreateTable(model.__table__).compile(dialect=postgresql.dialect())).replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ") + ";")
    lines.extend(schema_lines)
    lines.append("")

    counts: dict[str, int] = {}
    with Session(engine) as db:
        for model in MODELS:
            table = model.__tablename__
            if table not in existing_tables:
                continue
            rows = db.execute(text(f'SELECT * FROM "{table}"')).mappings().all()
            counts[table] = len(rows)
            columns = [column.name for column in model.__table__.columns]
            quoted_columns = ", ".join(f'"{column}"' for column in columns)
            for row in rows:
                values = ", ".join(sql_value(row[column.name], column) for column in model.__table__.columns)
                lines.append(
                    f'INSERT INTO "{table}" ({quoted_columns}) VALUES ({values}) '
                    "ON CONFLICT DO NOTHING;"
                )
            lines.append("")

    lines.extend([
        "COMMIT;",
        "",
        "-- Row counts from SQLite:",
    ])
    lines.extend(f"-- {table}: {count}" for table, count in counts.items())
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Exported: {output_path}")
    for table, count in counts.items():
        print(f"{table}: {count}")


if __name__ == "__main__":
    main()
